const Elementolivros = document.querySelectorAll(".livro");

Elementolivros.forEach(livro => {

    livro.addEventListener("click", () => {

        window.location.href = "analise.html?livro=" + livro.id;

        livro.classList.add("abrindo");

        document.body.classList.add("saindo");

        setTimeout(() => {

            window.location.href = "analise.html?livro=" + livro.id;

        }, 600);

    });

});

const voltar = document.querySelector(".voltar");

    voltar.addEventListener("click", (evento) => {

        evento.preventDefault();

        document.body.classList.add("saindo");

        setTimeout(() => {

            window.location.href = "index.html";

    }, 1000);

});


const parametros = new URLSearchParams(window.location.search);

const livroEscolhido = parametros.get("livro");

const livro = livros[livroEscolhido];

